#!/usr/bin/env python3
"""Refresh packaged notices after changing the Rust engine's dependencies."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parent.parent
workspace = root / "engine-rs"
target = "aarch64-linux-android"


def cargo(*args):
    return subprocess.check_output(["cargo", *args], cwd=workspace, text=True)


packages = {(p["name"], p["version"]): p for p in json.loads(
    cargo("metadata", "--format-version", "1", "--locked"))["packages"]}
linked = set()
for line in cargo("tree", "-p", "wt-engine", "--locked", "--target", target, "-e", "normal",
                  "--prefix", "none", "--format", "{p}").splitlines():
    name, version = line.split()[:2]
    linked.add((name, version.lstrip("v")))

notices = ["Third-party notices for the native Rust engine.\n"
           "Generated by scripts/update-rust-notices.py from linked crates.\n"
           "Versions and checksums: engine-rs/Cargo.lock.\n"]
count = 0
for key in sorted(linked):
    package = packages[key]
    if package["source"] is None:  # This workspace's own crates.
        continue
    count += 1
    folder = Path(package["manifest_path"]).parent
    files = sorted(p for p in folder.iterdir() if p.is_file()
                   and p.name.lower().startswith(("license", "licence", "copying", "notice")))
    header = f"\n{'=' * 72}\n{key[0]} {key[1]} — {package.get('license') or 'see crate'}\n"
    # Crates that ship no license file are covered by their declared SPDX terms.
    notices.append(header if not files else "".join(
        f"{header}{file.name}\n\n{file.read_text(errors='replace')}" for file in files))
output = root / "android/app/src/main/assets/licenses/rust-dependencies.txt"
output.write_text("\n".join(notices))
print(f"Packaged notices for {count} crates ({output.stat().st_size} bytes).")
